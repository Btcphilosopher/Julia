using Dates

# ============================================================
# קאַנפיגוראַציע
# ============================================================

const KLINGEL_DAUER = 1.5          # Sekunden
const ABSTAND_ZWISCHEN_KLINGELN = 3.0
const ÖFFNUNGSSTUNDE = 8
const SCHLIESSSTUNDE = 20

# ============================================================
# דאַטע־סטרוקטורן
# ============================================================

mutable struct סענסער
    באמערקט::Bool
end

mutable struct קלינגל
    אקטיוו::Bool
    ציילער::Int
end

mutable struct דעלי_סיסטעם
    סענסער::סענסער
    קלינגל::קלינגל
    לעצטע_קלינגל::Float64
    אָפֿן::Bool
end

# ============================================================
# סיסטעם־אויפשטעלונג
# ============================================================

סיסטעם = דעלי_סיסטעם(
    סענסער(false),
    קלינגל(false, 0),
    -Inf,
    true
)

# ============================================================
# עפֿענען שעה־קאָנטראָל
# ============================================================

function דעלי_איז_אָפֿן()

    שעה = Dates.hour(now())

    return שעה >= ÖFFNUNGSSTUNDE &&
           שעה < SCHLIESSSTUNDE
end

# ============================================================
# סענסער־דעטעקציע
# ============================================================

function קונה_דעטעקטירט!(
    סיסטעם::דעלי_סיסטעם
)

    סיסטעם.סענסער.באמערקט = true

    println()
    println("קונה דעטעקטירט!")
    println("א מענטש קומט אַרײַן אין דעלי.")

end

# ============================================================
# קלינגל אַקטיוויזירן
# ============================================================

function קלינגל_אקטיוויזירן!(
    סיסטעם::דעלי_סיסטעם
)

    איצט = time()

    # קאָנטראָלירן די צייט צווישן קלינגלען
    if איצט - סיסטעם.לעצטע_קלינגל <
       ABSTAND_ZWISCHEN_KLINGELN

        println(
            "קלינגל איז נאָך אין קולדאַון."
        )

        return false
    end

    if !דעלי_איז_אָפֿן()

        println(
            "די דעלי איז איצט פֿאַרמאַכט."
        )

        return false
    end

    סיסטעם.קלינגל.אקטיוו = true

    סיסטעם.קלינגל.ציילער += 1

    סיסטעם.לעצטע_קלינגל = איצט

    println()
    println("🔔 דינג־דאָנג!")
    println("ברוכים הבאים!")
    println(
        "קונה־ציילער: ",
        סיסטעם.קלינגל.ציילער
    )

    # דאָ וואָלט מען אין אַ פאַקטישן סיסטעם
    # אַקטיוויזירט דעם פיזישן רעלע / GPIO.

    sleep(KLINGEL_DAUER)

    קלינגל_אויסמאַכן!(
        סיסטעם
    )

    return true
end

# ============================================================
# קלינגל אויסמאַכן
# ============================================================

function קלינגל_אויסמאַכן!(
    סיסטעם::דעלי_סיסטעם
)

    סיסטעם.קלינגל.אקטיוו = false

    println(
        "קלינגל איז אויסגעמאַכט."
    )

end

# ============================================================
