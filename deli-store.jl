    println()
    println("--------------------------------------------")
    println("סענסער־קאָנטראָל")

    if סיסטעם.סענסער.באמערקט

        println(
            "מענטש דעטעקטירט."
        )

        קלינגל_אקטיוויזירן!(
            סיסטעם
        )

        סענסער_צוריקשטעלן!(
            סיסטעם
        )

    else

        println(
            "קיין קונה נישט דעטעקטירט."
