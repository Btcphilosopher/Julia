# ============================================================
# 电池热功率优化器
# Julia
#
# 目的：
# 通过热管理寻找电池的最佳工作温度，
# 在安全温度范围内最大化瞬时输出功率。
# ============================================================

struct 电池参数
    标称电压::Float64
    内阻_25C::Float64
    容量_Ah::Float64
    最低温度::Float64
    最佳温度::Float64
    最高温度::Float64
end


struct 热参数
    热容量::Float64
    散热系数::Float64
    加热功率::Float64
end


mutable struct 电池状态
    温度::Float64
    SOC::Float64
end


# ------------------------------------------------------------
# 温度对内阻的影响
# 这里使用简化模型进行研究
# ------------------------------------------------------------

function 计算内阻(
    电池::电池参数,
    温度::Float64
)

    温差 = 温度 - 电池.最佳温度

    # 离最佳温度越远，内阻越高
    修正系数 = 1.0 + 0.004 * 温差^2

    return 电池.内阻_25C * 修正系数
end


# ------------------------------------------------------------
# 计算最大理论输出功率
# 对简化的 Thevenin 电池模型：
#
# Pmax ≈ V² / (4R)
# ------------------------------------------------------------

function 最大输出功率(
    电池::电池参数,
    状态::电池状态
)

    内阻 = 计算内阻(
        电池,
        状态.温度
    )

    return 电池.标称电压^2 / (4 * 内阻)
end


# ------------------------------------------------------------
# 电池热模型
# ------------------------------------------------------------

function 更新温度!(
    电池::电池参数,
    热::热参数,
    状态::电池状态,
    时间步长::Float64
)

    当前功率 = 最大输出功率(
        电池,
        状态
    )

    # 电流的简化估计
    电流 = 当前功率 / 电池.标称电压

    内阻 = 计算内阻(
        电池,
        状态.温度
    )

    # Joule heating
    电阻发热 = 电流^2 * 内阻

    # 与环境的散热
    环境温度 = 25.0

    散热 = 热.散热系数 *
           (状态.温度 - 环境温度)

    净热功率 =
        热.加热功率 +
        电阻发热 -
        散热

    温度变化 =
        净热功率 /
        热.热容量 *
        时间步长

    状态.温度 += 温度变化

    return 状态.温度
end


# ------------------------------------------------------------
# 热管理控制器
# ------------------------------------------------------------

function 热管理!(
    电池::电池参数,
    热::热参数,
    状态::电池状态
)

    if 状态.温度 < 电池.最佳温度 - 2

        println("正在加热电池……")

    elseif 状态.温度 > 电池.最佳温度 + 2

        println("正在降低电池温度……")

    else

        println("电池处于最佳温度区间")

    end
end


# ------------------------------------------------------------
# 扫描不同温度
# 找出理论最大功率点
# ------------------------------------------------------------

function 寻找最佳温度(
    电池::电池参数
)

    最佳温度 = 电池.最低温度
    最大功率 = 0.0

    for 温度 in 电池.最低温度:0.5:电池.最高温度

        状态 = 电池状态(
            温度,
            0.8
        )

        功率 = 最大输出功率(
            电池,
            状态
        )

        if 功率 > 最大功率

            最大功率 = 功率
            最佳温度 = 温度

        end
    end

    println()
    println("========== 优化结果 ==========")
    println(
        "最佳工作温度：",
        最佳温度,
        " °C"
    )

    println(
        "理论最大功率：",
        round(最大功率, digits=2),
        " W"
    )

    return 最佳温度, 最大功率
end


# ============================================================
# 示例
# ============================================================

电池 = 电池参数(
    400.0,     # 标称电压
    0.05,      # 25°C 内阻
    100.0,     # Ah
    0.0,       # 最低温度
    25.0,      # 最佳温度
    45.0       # 最高温度
)


热 = 热参数(
    50000.0,   # 热容量
    80.0,      # 散热系数
    2000.0     # 加热功率
)


状态 = 电池状态(
    10.0,      # 初始温度
    0.80       # SOC
)


寻找最佳温度(电池)

println()

for t in 1:10

    热管理!(
        电池,
        热,
        状态
    )

    更新温度!(
        电池,
        热,
        状态,
        1.0
    )

    功率 = 最大输出功率(
        电池,
        状态
    )

    println(
        "时间 = ", t,
        " s | 温度 = ",
        round(状态.温度, digits=2),
        " °C | 最大功率 = ",
        round(功率, digits=2),
        " W"
    )
end
