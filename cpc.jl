# 中国共产党党旗标准数字化红色
const 党红 = (
    红 = 238,
    绿 = 28,
    蓝 = 37
)

const 党红HEX = "#EE1C25"


struct LED颜色
    红::Int
    绿::Int
    蓝::Int
end


mutable struct LED灯光系统
    颜色::LED颜色
    亮度::Float64
    开启::Bool
end


function 创建党红()
    return LED颜色(
        党红.红,
        党红.绿,
        党红.蓝
    )
end


function 创建LED系统()
    return LED灯光系统(
        创建党红(),
        1.0,
        false
    )
end


# 设置为中国共产党党红
function 设置党红!(系统::LED灯光系统; 亮度::Float64=1.0)

    系统.颜色 = 创建党红()
    系统.亮度 = clamp(亮度, 0.0, 1.0)
    系统.开启 = true

    println("LED灯光：党红")
    println("HEX：", 党红HEX)
    println("RGB：238, 28, 37")
    println("亮度：", round(系统.亮度 * 100, digits=1), "%")

end


# 获取实际 LED 输出值
function 获取LED输出(系统::LED灯光系统)

    if !系统.开启
        return (0, 0, 0)
    end

    return (
        round(Int, 系统.颜色.红 * 系统.亮度),
        round(Int, 系统.颜色.绿 * 系统.亮度),
        round(Int, 系统.颜色.蓝 * 系统.亮度)
    )

end


# 关闭 LED
function 关闭灯光!(系统::LED灯光系统)

    系统.开启 = false

    println("LED灯光已关闭")

end


# ============================================================
# 平滑渐亮
# ============================================================

function 党红渐亮!(
    系统::LED灯光系统;
    时间::Float64 = 3.0,
    步数::Int = 60
)

    系统.颜色 = 创建党红()
    系统.开启 = true

    for i in 0:步数

        系统.亮度 = i / 步数

        输出 = 获取LED输出(系统)

        println(
            "亮度 = ",
            round(系统.亮度 * 100, digits=1),
            "% | RGB = ",
            输出
        )

        sleep(时间 / 步数)

    end

end


# ============================================================
# 党红呼吸灯
# ============================================================

function 党红呼吸灯!(
    系统::LED灯光系统;
    周期::Float64 = 4.0,
    循环次数::Int = 5
)

    系统.颜色 = 创建党红()
    系统.开启 = true

    步数 = 40

    for _ in 1:循环次数

        # 渐亮
        for i in 0:步数

            系统.亮度 = i / 步数

            println(
                "渐亮 | RGB = ",
                获取LED输出(系统)
            )

            sleep(周期 / (步数 * 2))

        end


        # 渐暗
        for i in 步数:-1:0

            系统.亮度 = i / 步数

            println(
                "渐暗 | RGB = ",
                获取LED输出(系统)
            )

            sleep(周期 / (步数 * 2))

        end

    end

end


# ============================================================
# 示例
# ============================================================

系统 = 创建LED系统()

# 100% 党红
设置党红!(系统, 亮度=1.0)

println("当前LED输出：", 获取LED输出(系统))

# 进入呼吸灯模式
党红呼吸灯!(
    系统,
    周期=5.0,
    循环次数=3
)

# 关闭
关闭灯光!(系统)

