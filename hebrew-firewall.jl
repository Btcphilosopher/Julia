using Dates
using Printf

# ------------------------------------------------------------
# סוגי פרוטוקולים
# ------------------------------------------------------------

@enum פרוטוקול TCP UDP ICMP

# ------------------------------------------------------------
# חבילת רשת
# ------------------------------------------------------------

struct חבילת_רשת
    כתובת_מקור::String
    כתובת_יעד::String
    יציאה_מקור::Int
    יציאה_יעד::Int
    פרוטוקול::פרוטוקול
    גודל::Int
    חותמת_זמן::DateTime
end

# ------------------------------------------------------------
# כלל חומת אש
# ------------------------------------------------------------

struct כלל_אש
    שם::String
    כתובת_מקור::Union{String,Nothing}
    כתובת_יעד::Union{String,Nothing}
    יציאה::Union{Int,Nothing}
    פרוטוקול::Union{פרוטוקול,Nothing}
    פעולה::Symbol
end

# ------------------------------------------------------------
# מצב חומת האש
# ------------------------------------------------------------

mutable struct חומת_אש
    כללים::Vector{כלל_אש}
    מנות_מאושרות::Int
    מנות_חסומות::Int
    מנות_נזרקות::Int
    חיבורים::Dict{String,DateTime}
    חסומים::Set{String}
end

# ------------------------------------------------------------
# יצירת חומת אש
# ------------------------------------------------------------

function צור_חומת_אש()

    return חומת_אש(
        כלל_אש[],
        0,
        0,
        0,
        Dict{String,DateTime}(),
        Set{String}()
    )

end

# ------------------------------------------------------------
# הוספת כלל
# ------------------------------------------------------------

function הוסף_כלל!(חומת::חומת_אש, כלל::כלל_אש)

    push!(חומת.כללים, כלל)

    println(
        "נוסף כלל: $(כלל.שם) → פעולה: $(כלל.פעולה)"
    )

end

# ------------------------------------------------------------
# בדיקת התאמת כלל
# ------------------------------------------------------------

function מתאים(חבילה::חבילת_רשת, כלל::כלל_אש)

    if כלל.כתובת_מקור !== nothing &&
       חבילה.כתובת_מקור != כלל.כתובת_מקור

        return false
    end

    if כלל.כתובת_יעד !== nothing &&
       חבילה.כתובת_יעד != כלל.כתובת_יעד

        return false
    end

    if כלל.יציאה !== nothing &&
       חבילה.יציאה_יעד != כלל.יציאה

        return false
    end

    if כלל.פרוטוקול !== nothing &&
       חבילה.פרוטוקול != כלל.פרוטוקול

        return false
    end

    return true
end

# ------------------------------------------------------------
# בדיקת חבילה
# ------------------------------------------------------------

function בדוק_חבילה!(
    חומת::חומת_אש,
    חבילה::חבילת_רשת
)

    # חסימה מיידית של כתובות ידועות

    if חבילה.כתובת_מקור in חומת.חסומים

        חומת.מנות_חסומות += 1

        println(
            "⛔ נחסמה כתובת ידועה: ",
            חבילה.כתובת_מקור
        )

        return :חסום
    end

    # בדיקת כללי החומה

    for כלל in חומת.כללים

        if מתאים(חבילה, כלל)

            if כלל.פעולה == :אפשר

                חומת.מנות_מאושרות += 1

                println(
                    "✓ אושרה חבילה באמצעות כלל: ",
                    כלל.שם
                )

                return :אפשר
            end

            if כלל.פעולה == :חסום

                חומת.מנות_חסומות += 1

                println(
                    "⛔ נחסמה חבילה באמצעות כלל: ",
                    כלל.שם
                )

                return :חסום
            end
        end
    end

    # ברירת מחדל: חסימה

    חומת.מנות_נזרקות += 1

    println(
        "⚠ החבילה לא התאימה לשום כלל — נחסמה"
    )

    return :חסום
end

# ------------------------------------------------------------
# מעקב חיבורים
# ------------------------------------------------------------

function רשום_חיבור!(
    חומת::חומת_אש,
    חבילה::חבילת_רשת
)

    מפתח = string(
        חבילה.כתובת_מקור,
        ":",
        חבילה.יציאה_מקור,
        "→",
        חבילה.כתובת_יעד,
        ":",
        חבילה.יציאה_יעד
    )

    חומת.חיבורים[מפתח] = now()

end

# ------------------------------------------------------------
# חסימת כתובת
# ------------------------------------------------------------

function חסום_כתובת!(
    חומת::חומת_אש,
    כתובת::String
)

    push!(חומת.חסומים, כתובת)

    println(
        "🚫 הכתובת נחסמה לצמיתות: ",
        כתובת
    )

end

# ------------------------------------------------------------
# יצירת חבילה
# ------------------------------------------------------------

function צור_חבילה(
    מקור,
    יעד,
    יציאה_מקור,
    יציאה_יעד,
    פרוטוקול,
    גודל
)

    return חבילת_רשת(
        מקור,
        יעד,
        יציאה_מקור,
        יציאה_יעד,
        פרוטוקול,
        גודל,
        now()
    )

end

# ------------------------------------------------------------
# ניטור חבילה
# ------------------------------------------------------------

function נתח_חבילה!(
    חומת::חומת_אש,
    חבילה::חבילת_רשת
)

    println()
    println("────────────────────────────────")
    println("ניתוח חבילת רשת")
    println("מקור: $(חבילה.כתובת_מקור)")
    println("יעד: $(חבילה.כתובת_יעד)")
    println("יציאת יעד: $(חבילה.יציאה_יעד)")
    println("פרוטוקול: $(חבילה.פרוטוקול)")
    println("גודל: $(חבילה.גודל) בתים")

    תוצאה = בדוק_חבילה!(חומת, חבילה)

    if תוצאה == :אפשר
        רשום_חיבור!(חומת, חבילה)
    end

    return תוצאה
end

# ------------------------------------------------------------
# סטטיסטיקות
# ------------------------------------------------------------

function הצג_סטטיסטיקות(חומת::חומת_אש)

    println()
    println("════════════════════════════════")
    println("סטטיסטיקות חומת האש")
    println("════════════════════════════════")

    println(
        "מנות שאושרו: ",
        חומת.מנות_מאושרות
    )

    println(
        "מנות שנחסמו: ",
        חומת.מנות_חסומות
    )

    println(
        "מנות שנזרקו: ",
        חומת.מנות_נזרקות
    )

    println(
        "חיבורים פעילים: ",
        length(חומת.חיבורים)
    )

    println(
        "כתובות חסומות: ",
        length(חומת.חסומים)
    )

end

