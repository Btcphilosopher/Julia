# ============================================================
# מערכת תאורת EDM חכמה
# מערכת תגובתית למוזיקה בזמן אמת
# ============================================================

using FFTW

# ------------------------------------------------------------
# הגדרות מערכת
# ------------------------------------------------------------

struct מערכת_תאורה
    מספר_גופים::Int
    קצב_עדכון::Float64
    בהירות_מקסימלית::Float64
end


struct פריים_מוזיקלי
    bpm::Float64
    בס::Float64
    מיד::Float64
    גבוה::Float64
    עוצמה::Float64
end


# ------------------------------------------------------------
# ניתוח ספקטרום
# ------------------------------------------------------------

function ניתוח_מוזיקה(
    אות::Vector{Float64},
    קצב_דגימה::Float64
)

    # FFT הופך את האות מתחום הזמן
    # לתחום התדר
    ספקטרום = abs.(rfft(אות))

    n = length(ספקטרום)

    # חלוקה גסה לתחומי תדר
    תחום_בס = ספקטרום[1:max(2, n ÷ 8)]
    תחום_מיד = ספקטרום[max(2, n ÷ 8):max(3, n ÷ 2)]
    תחום_גבוה = ספקטרום[max(3, n ÷ 2):end]

    בס = mean(תחום_בס)
    מיד = mean(תחום_מיד)
    גבוה = mean(תחום_גבוה)

    עוצמה = mean(abs2, אות)

    return בס, מיד, גבוה, עוצמה
end


# ------------------------------------------------------------
# זיהוי ביט
# ------------------------------------------------------------

function זיהוי_ביט(
    אות::Vector{Float64},
    סף::Float64
)

    אנרגיה = mean(abs2, אות)

    return אנרגיה > סף
end


# ------------------------------------------------------------
# יצירת פריים תאורה
# ------------------------------------------------------------

function יצירת_פריים(
    בס,
    מיד,
    גבוה,
    עוצמה,
    bpm
)

    return פריים_מוזיקלי(
        bpm,
        בס,
        מיד,
        גבוה,
        עוצמה
    )
end


# ------------------------------------------------------------
# מיפוי מוזיקה לתאורה
# ------------------------------------------------------------

function מיפוי_תאורה(
    פריים::פריים_מוזיקלי,
    מערכת::מערכת_תאורה
)

    # בס → עוצמת תאורת הבס
    עוצמת_בס =
        clamp(
            פריים.בס * 2.0,
            0.0,
            מערכת.בהירות_מקסימלית
        )

    # תדרים בינוניים → תנועת צבע
    עוצמת_מיד =
        clamp(
            פריים.מיד * 2.0,
            0.0,
            מערכת.בהירות_מקסימלית
        )

    # תדרים גבוהים → הבזקי Strobe
    עוצמת_גבוה =
        clamp(
            פריים.גבוה * 3.0,
            0.0,
            מערכת.בהירות_מקסימלית
        )

    return (
        בס = עוצמת_בס,
        מיד = עוצמת_מיד,
        גבוה = עוצמת_גבוה
    )
end


# ------------------------------------------------------------
# מנוע Beat
# ------------------------------------------------------------

function מנוע_ביט(
    פריים::פריים_מוזיקלי
)

    פעימה =
        פריים.עוצמה > 0.5

    if פעימה
        return :BEAT
    else
        return :שקט
    end
end


# ------------------------------------------------------------
# יצירת אפקט EDM
# ------------------------------------------------------------

function אפקט_EDM(
    פריים::פריים_מוזיקלי,
    מערכת::מערכת_תאורה
)

    תאורה = מיפוי_תאורה(
        פריים,
        מערכת
    )

    ביט = מנוע_ביט(פריים)

    println("================================")
    println("      EDM LIGHT ENGINE")
    println("================================")

    println("BPM: ", round(
        פריים.bpm,
        digits=1
    ))

    println(
        "בס: ",
        round(תאורה.בס, digits=2)
    )

    println(
        "מיד: ",
        round(תאורה.מיד, digits=2)
    )

    println(
        "גבוהים: ",
        round(תאורה.גבוה, digits=2)
    )

    println("מצב: ", ביט)

    if ביט == :BEAT

        println("אפקט: הבזק ביט")

    else

        println("אפקט: תאורת אווירה")

    end
end


# ------------------------------------------------------------
# מערכת לדוגמה
# ------------------------------------------------------------

מערכת = מערכת_תאורה(
    24,       # מספר גופי תאורה
    60.0,     # 60 עדכונים לשנייה
    1.0       # בהירות מקסימלית
)


# ------------------------------------------------------------
# אות מוזיקלי מדומה
# ------------------------------------------------------------

קצב_דגימה = 44100.0

זמן = range(
    0,
    1,
    length=44100
)

אות =
    0.8 .* sin.(2π .* 60 .* זמן) .+
    0.3 .* sin.(2π .* 800 .* זמן) .+
    0.15 .* sin.(2π .* 6000 .* זמן)


# ------------------------------------------------------------
# ניתוח
# ------------------------------------------------------------

בס, מיד, גבוה, עוצמה =
    ניתוח_מוזיקה(
        אות,
        קצב_דגימה
    )


# ------------------------------------------------------------
# יצירת פריים
# ------------------------------------------------------------

פריים = יצירת_פריים(
    בס,
    מיד,
    גבוה,
    עוצמה,
    128.0
)


# ------------------------------------------------------------
# הפעלת מנוע התאורה
# ------------------------------------------------------------

אפקט_EDM(
    פריים,
    מערכת
)

