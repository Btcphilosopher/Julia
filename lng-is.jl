# ============================================================
# מערכת ניטור ואופטימיזציה לגנרטור LNG
# LNG GENERATOR MONITORING & OPTIMIZATION
# ============================================================

using Statistics


# ------------------------------------------------------------
# מבנה נתוני הגנרטור
# ------------------------------------------------------------

struct גנרטורLNG

    הספק_נומינלי::Float64       # MW
    יעילות_חשמלית::Float64      # 0-1

    טמפרטורה_מקסימלית::Float64 # °C
    לחץ_מקסימלי::Float64        # bar

    קצב_דלק_מקסימלי::Float64    # kg/s
end


# ------------------------------------------------------------
# מצב תפעולי
# ------------------------------------------------------------

mutable struct מצב_גנרטור

    עומס::Float64               # MW
    טמפרטורה::Float64           # °C
    לחץ::Float64                # bar

    צריכת_LNG::Float64          # kg/s
    הספק_חשמלי::Float64         # MW

    זמן_פעולה::Float64          # שעות
end


# ------------------------------------------------------------
# פרמטרים של LNG
# ------------------------------------------------------------

const ערך_חימום_LNG = 50.0
# MJ/kg — ערך חימום משוער לצורך הסימולציה


# ------------------------------------------------------------
# חישוב צריכת LNG
# ------------------------------------------------------------

function צריכת_LNG(
    הספק::Float64,
    יעילות::Float64
)

    # הספק חשמלי → אנרגיה תרמית
    אנרגיה_תרמית =
        הספק / יעילות

    # המרה מ-MW ל-MJ/s
    אנרגיה_לשנייה =
        אנרגיה_תרמית

    return אנרגיה_לשנייה /
           ערך_חימום_LNG
end


# ------------------------------------------------------------
# חישוב יעילות
# ------------------------------------------------------------

function חשב_יעילות(
    הספק::Float64,
    צריכת::Float64
)

    if צריכת <= 0
        return 0.0
    end

    אנרגיה_נכנסת =
        צריכת * ערך_חימום_LNG

    return הספק / אנרגיה_נכנסת
end


# ------------------------------------------------------------
# חישוב טמפרטורה משוערת
# ------------------------------------------------------------

function טמפרטורת_גנרטור(
    עומס::Float64,
    טמפרטורת_סביבה::Float64
)

    # מודל פשוט לצורך סימולציה
    עליית_טמפרטורה =
        35.0 * עומס^1.2

    return טמפרטורת_סביבה +
           עליית_טמפרטורה
end


# ------------------------------------------------------------
# חישוב לחץ מערכת
# ------------------------------------------------------------

function לחץ_מערכת(
    עומס::Float64
)

    לחץ_בסיס = 5.0

    return לחץ_בסיס +
           2.0 * עומס
end


# ------------------------------------------------------------
# הערכת מצב
# ------------------------------------------------------------

function בדיקת_בטיחות(
    גנרטור::גנרטורLNG,
    מצב::מצב_גנרטור
)

    התראות = String[]

    if מצב.טמפרטורה >
       גנרטור.טמפרטורה_מקסימלית

        push!(
            התראות,
            "טמפרטורה גבוהה"
        )
    end

    if מצב.לחץ >
       גנרטור.לחץ_מקסימלי

        push!(
            התראות,
            "לחץ גבוה"
        )
    end

    if מצב.צריכת_LNG >
       גנרטור.קצב_דלק_מקסימלי

        push!(
            התראות,
            "צריכת LNG גבוהה מדי"
        )
    end

    return התראות
end


# ------------------------------------------------------------
# אופטימיזציית עומס
# ------------------------------------------------------------

function עומס_אופטימלי(
    גנרטור::גנרטורLNG,
    דרישה::Float64
)

    # שמירה על מרווח תפעולי
    עומס_מקסימלי =
        0.90 * גנרטור.הספק_נומינלי

    return clamp(
        דרישה,
        0.0,
        עומס_מקסימלי
    )
end


# ------------------------------------------------------------
# עדכון מצב הגנרטור
# ------------------------------------------------------------

function עדכן_גנרטור!(
    גנרטור::גנרטורLNG,
    מצב::מצב_גנרטור,
    דרישה::Float64,
    טמפרטורת_סביבה::Float64,
    dt::Float64
)

    # בחירת עומס
    מצב.עומס =
        עומס_אופטימלי(
            גנרטור,
            דרישה
        )

    # הספק חשמלי
    מצב.הספק_חשמלי =
        מצב.עומס

    # צריכת LNG
    מצב.צריכת_LNG =
        צריכת_LNG(
            מצב.הספק_חשמלי,
            גנרטור.יעילות_חשמלית
        )

    # טמפרטורה
    מצב.טמפרטורה =
        טמפרטורת_גנרטור(
            מצב.עומס,
            טמפרטורת_סביבה
        )

    # לחץ
    מצב.לחץ =
        לחץ_מערכת(
            מצב.עומס
        )

    # זמן פעולה
    מצב.זמן_פעולה += dt

    return מצב
end


# ------------------------------------------------------------
# דוח תפעולי
# ------------------------------------------------------------

function דוח_מצב(
    גנרטור::גנרטורLNG,
    מצב::מצב_גנרטור
)

    println()
    println("==========================================")
    println("       מערכת ניטור גנרטור LNG")
    println("==========================================")

    println(
        "הספק: ",
        round(מצב.הספק_חשמלי, digits=2),
        " MW"
    )

    println(
        "עומס: ",
        round(
            100 * מצב.עומס /
            גנרטור.הספק_נומינלי,
            digits=1
        ),
        "%"
    )

    println(
        "צריכת LNG: ",
        round(מצב.צריכת_LNG, digits=4),
        " kg/s"
    )

    println(
        "טמפרטורה: ",
        round(מצב.טמפרטורה, digits=1),
        " °C"
    )

    println(
        "לחץ: ",
        round(מצב.לחץ, digits=2),
        " bar"
    )

    println(
        "זמן פעולה: ",
        round(מצב.זמן_פעולה, digits=2),
        " שעות"
    )

    התראות =
        בדיקת_בטיחות(
            גנרטור,
            מצב
        )

    if isempty(התראות)

        println("מצב מערכת: תקין")

    else

        println("מצב מערכת: התראה")

        for התראה in התראות
            println("⚠ ", התראה)
        end
    end

    println("==========================================")
end


# ------------------------------------------------------------
# יצירת גנרטור
# ------------------------------------------------------------

גנרטור = גנרטורLNG(

    10.0,    # 10 MW
    0.42,    # 42% יעילות

    700.0,   # °C
    12.0,    # bar

    0.50     # kg/s
)


# ------------------------------------------------------------
# מצב התחלתי
# ------------------------------------------------------------

מצב = מצב_גנרטור(

    0.0,
    25.0,
    5.0,

    0.0,
    0.0,

    0.0
)


# ------------------------------------------------------------
# סימולציה
# ------------------------------------------------------------

טמפרטורת_סביבה = 20.0

דרישות_הספק = [
    2.0,
    4.0,
    6.0,
    8.0,
    9.0,
    7.0,
    5.0,
    3.0
]


for דרישה in דרישות_הספק

    עדכן_גנרטור!(
        גנרטור,
        מצב,
        דרישה,
        טמפרטורת_סביבה,
        1.0
    )

    דוח_מצב(
        גנרטור,
        מצב
    )
end

