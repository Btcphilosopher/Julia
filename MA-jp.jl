using LinearAlgebra
using Statistics

# ------------------------------------------------------------
# 物体を表す構造体
# ------------------------------------------------------------

struct 物体
    名前::String
    位置::Vector{Float64}      # [x, y, z] メートル
    速度::Vector{Float64}      # [vx, vy, vz] m/s
    大きさ::Float64            # おおよその半径
end

# ------------------------------------------------------------
# ロボット本体
# ------------------------------------------------------------

struct ロボット
    位置::Vector{Float64}
    速度::Vector{Float64}
    認識距離::Float64
    安全距離::Float64
end

# ------------------------------------------------------------
# 2点間の距離
# ------------------------------------------------------------

function 距離(a::Vector{Float64}, b::Vector{Float64})
    return norm(a - b)
end

# ------------------------------------------------------------
# 接近速度を計算
# 正の値 = 接近
# ------------------------------------------------------------

function 接近速度(ロボット位置, ロボット速度,
                  物体位置, 物体速度)

    相対位置 = 物体位置 - ロボット位置
    相対速度 = 物体速度 - ロボット速度

    d = norm(相対位置)

    if d < 1e-6
        return 0.0
    end

    方向 = 相対位置 / d

    # 相対速度が物体との距離を縮める方向か判定
    return -dot(相対速度, 方向)
end

# ------------------------------------------------------------
# 物体の危険度を評価
# ------------------------------------------------------------

function 危険度評価(r::ロボット, o::物体)

    d = 距離(r.位置, o.位置)
    接近 = 接近速度(r.位置, r.速度, o.位置, o.速度)

    if d <= r.安全距離
        return "危険"

    elseif d <= r.安全距離 * 2 && 接近 > 0.2
        return "注意"

    elseif d <= r.認識距離
        return "監視"

    else
        return "安全"
    end
end

# ------------------------------------------------------------
# 衝突までのおおよその時間
# ------------------------------------------------------------

function 衝突予測時間(r::ロボット, o::物体)

    d = 距離(r.位置, o.位置)
    v = 接近速度(r.位置, r.速度, o.位置, o.速度)

    if v <= 0
        return Inf
    end

    return d / v
end

# ------------------------------------------------------------
# 周辺環境をスキャン
# ------------------------------------------------------------

function 環境認識(r::ロボット, 物体一覧)

    println("================================")
    println("   ロボット周辺認識システム")
    println("================================")

    for o in 物体一覧

        d = 距離(r.位置, o.位置)

        # 認識範囲外は無視
        if d > r.認識距離
            continue
        end

        状態 = 危険度評価(r, o)
        ttc = 衝突予測時間(r, o)

        println()
        println("対象物: ", o.名前)
        println("距離: ", round(d, digits=2), " m")
        println("状態: ", 状態)

        if isfinite(ttc)
            println("衝突予測: ",
                    round(ttc, digits=2), " 秒")
        else
            println("衝突予測: なし")
        end

        if 状態 == "危険"
            println("⚠ 緊急停止が必要")
        elseif 状態 == "注意"
            println("⚠ 速度を低下してください")
        elseif 状態 == "監視"
            println("→ 継続監視")
        else
            println("✓ 安全")
        end
    end
end

