# ============================================================
# 智能电饭煲控制系统
# Julia
#
# 功能：
# 1. 自动识别米量
# 2. 自动计算加水量
# 3. 温度闭环控制
# 4. 浸泡 → 加热 → 沸腾 → 焖饭 → 保温
# 5. 防止温度过高
