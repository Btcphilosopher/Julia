# ============================================================
# 1. 烹饪阶段
# ============================================================

@enum 烹饪阶段 begin
    待机
    浸泡
    快速加热
    沸腾
    焖饭
    保温
    完成
    错误
end


# ============================================================
# 2. 电饭煲传感器
# ============================================================

mutable struct 传感器数据

    锅内温度::Float64
    锅底温度::Float64

    蒸汽压力::Float64

    米量::Float64
    水量::Float64

    锅盖关闭::Bool
    内锅存在::Bool

    电源电压::Float64

end


# ============================================================
# 3. 加热器
# ============================================================

mutable struct 加热系统

    最大功率::Float64
    当前功率::Float64

    温度目标::Float64

    加热开启::Bool

end


# ============================================================
# 4. 电饭煲系统
# ============================================================

mutable struct 智能电饭煲

    传感器::传感器数据
    加热器::加热系统

    当前阶段::烹饪阶段

    烹饪模式::String

    剩余时间::Float64

    烹饪开始时间::Union{Nothing,DateTime}

    错误信息::String

end


# ============================================================
# 5. 创建电饭煲
# ============================================================

function 创建电饭煲()

    传感器 = 传感器数据(

        25.0,       # 锅内温度
        25.0,       # 锅底温度

        0.0,        # 压力

        0.0,        # 米量
        0.0,        # 水量

        true,       # 锅盖
        true,       # 内锅

        230.0       # 电压
    )


    加热器 = 加热系统(

        1200.0,     # 最大功率 W
        0.0,

        100.0,

        false
    )


    return 智能电饭煲(

        传感器,
        加热器,

        待机,

        "标准米饭",

        0.0,

        nothing,

        ""
    )

end


# ============================================================
# 6. 设置米量
# ============================================================

function 设置米量!(
    电饭煲::智能电饭煲,
    米量::Float64
)

    if 米量 <= 0

        电饭煲.错误信息 =
            "米量必须大于零"

        电饭煲.当前阶段 =
            错误

        return false
    end


    电饭煲.传感器.米量 =
        米量


    # 标准米水比例
    电饭煲.传感器.水量 =
        米量 * 1.2


    println(
        "米量：",
        米量,
        " g"
    )

    println(
        "建议水量：",
        round(
            电饭煲.传感器.水量,
            digits=1
        ),
        " ml"
    )


    return true

end


# ============================================================
# 7. 设置烹饪模式
# ============================================================

function 设置烹饪模式!(
    电饭煲::智能电饭煲,
    模式::String
)

    支持模式 = [
        "标准米饭",
        "快速饭",
        "软饭",
        "硬饭",
        "粥",
        "保温"
    ]


    if !(模式 in 支持模式)

        电饭煲.错误信息 =
            "不支持的烹饪模式"

        电饭煲.当前阶段 =
            错误

        return false
    end


    电饭煲.烹饪模式 = 模式

    return true

end


# ============================================================
# 8. 根据模式设置参数
# ============================================================

function 获取烹饪参数(
    模式::String
)

    if 模式 == "标准米饭"

        return (
            浸泡时间=10.0,
            沸腾温度=100.0,
            焖饭时间=12.0,
            保温温度=70.0
        )

    elseif 模式 == "快速饭"

        return (
            浸泡时间=3.0,
            沸腾温度=100.0,
            焖饭时间=8.0,
            保温温度=70.0
        )

    elseif 模式 == "软饭"

        return (
            浸泡时间=15.0,
            沸腾温度=100.0,
            焖饭时间=18.0,
            保温温度=70.0
        )

    elseif 模式 == "硬饭"

        return (
            浸泡时间=5.0,
            沸腾温度=100.0,
            焖饭时间=8.0,
            保温温度=70.0
        )

    elseif 模式 == "粥"

        return (
            浸泡时间=20.0,
            沸腾温度=98.0,
            焖饭时间=30.0,
            保温温度=70.0
        )

    else

        return (
            浸泡时间=0.0,
            沸腾温度=100.0,
            焖饭时间=0.0,
            保温温度=70.0
        )

    end

end


# ============================================================
# 9. 安全检查
# ============================================================

function 安全检查!(
    电饭煲::智能电饭煲
)

    传感器 = 电饭煲.传感器


    # 没有内锅
    if !传感器.内锅存在

        电饭煲.加热器.当前功率 = 0.0
        电饭煲.加热器.加热开启 = false

        电饭煲.错误信息 =
            "未检测到内锅"

        电饭煲.当前阶段 =
            错误

        return false

    end


    # 锅盖异常
    if !传感器.锅盖关闭

        电饭煲.加热器.当前功率 = 0.0
        电饭煲.加热器.加热开启 = false

        电饭煲.错误信息 =
            "锅盖未关闭"

        return false

    end


    # 极端温度保护
    if 传感器.锅底温度 > 150.0

        电饭煲.加热器.当前功率 = 0.0
        电饭煲.加热器.加热开启 = false

        电饭煲.错误信息 =
            "锅底温度过高"

        电饭煲.当前阶段 =
            错误

        return false

    end


    return true

end


# ============================================================
# 10. 温度控制器
# ============================================================

function 温度控制!(
    电饭煲::智能电饭煲,
    目标温度::Float64
)

    当前温度 =
        电饭煲.传感器.锅内温度


    温差 =
        目标温度 - 当前温度


    # 简单比例控制器
    比例增益 = 30.0

    功率 =
        比例增益 * 温差


    # 温度远低于目标值时快速加热
    if 温差 > 15

        功率 =
            电饭煲.加热器.最大功率

    end


    电饭煲.加热器.当前功率 =
        clamp(
            功率,
            0.0,
            电饭煲.加热器.最大功率
        )


    电饭煲.加热器.加热开启 =
        电饭煲.加热器.当前功率 > 0

end


# ============================================================
# 11. 简化热力学模型
# ============================================================

function 更新温度!(
    电饭煲::智能电饭煲,
    dt::Float64
)

    传感器 =
        电饭煲.传感器

    加热器 =
        电饭煲.加热器


    # 简化的锅体热容量
    热容量 = 2500.0


    # 加热产生的热量
    输入热量 =
        加热器.当前功率 * dt


    # 向环境散热
    环境温度 = 22.0

    散热 =
        max(
            0.0,
            (传感器.锅内温度 -
             环境温度) * 8.0 * dt
        )


    # 温度变化
    温度变化 =
        (输入热量 - 散热) /
        热容量


    传感器.锅内温度 +=
        温度变化


    # 锅底温度略高
    传感器.锅底温度 =
        传感器.锅内温度 +
        加热器.当前功率 / 1000.0

end


# ============================================================
# 12. 蒸汽压力模拟
# ============================================================

function 更新压力!(
    电饭煲::智能电饭煲
)

    温度 =
        电饭煲.传感器.锅内温度


    if 温度 < 90

        电饭煲.传感器.蒸汽压力 = 0.0

    elseif 温度 < 100

        电饭煲.传感器.蒸汽压力 =
            (温度 - 90) * 0.02

    else

        电饭煲.传感器.蒸汽压力 =
            min(
                2.0,
                (温度 - 95) * 0.05
            )

    end

end


# ============================================================
# 13. 开始烹饪
# ============================================================

function 开始烹饪!(
    电饭煲::智能电饭煲
)

    if 电饭煲.传感器.米量 <= 0

        电饭煲.错误信息 =
            "请先加入米"

        电饭煲.当前阶段 =
            错误

        return false

    end


    if !安全检查!(电饭煲)

        return false

    end


    电饭煲.烹饪开始时间 =
        now()


    电饭煲.当前阶段 =
        浸泡


    电饭煲.剩余时间 =
        获取烹饪参数(
            电饭煲.烹饪模式
        ).浸泡时间 * 60


    println(
        "开始烹饪：",
        电饭煲.烹饪模式
    )


    return true

end


# ============================================================
# 14. 烹饪状态机
# ============================================================

function 更新烹饪状态!(
    电饭煲::智能电饭煲,
    dt::Float64
)

    参数 =
        获取烹饪参数(
            电饭煲.烹饪模式
        )


    电饭煲.剩余时间 =
        max(
            0.0,
            电饭煲.剩余时间 - dt
        )


    # --------------------------------------------------------
    # 浸泡
    # --------------------------------------------------------

    if 电饭煲.当前阶段 == 浸泡

        电饭煲.加热器.当前功率 = 0.0

        if 电饭煲.剩余时间 <= 0

            电饭煲.当前阶段 =
                快速加热

        end


    # --------------------------------------------------------
    # 快速加热
    # --------------------------------------------------------

    elseif 电饭煲.当前阶段 == 快速加热

        温度控制!(
            电饭煲,
            参数.沸腾温度
        )

        if 电饭煲.传感器.锅内温度 >=
           参数.沸腾温度 - 1

            电饭煲.当前阶段 =
                沸腾

            电饭煲.剩余时间 =
                5.0 * 60

        end


    # --------------------------------------------------------
    # 沸腾
    # --------------------------------------------------------

    elseif 电饭煲.当前阶段 == 沸腾

        温度控制!(
            电饭煲,
            参数.沸腾温度
        )

        if 电饭煲.剩余时间 <= 0

            电饭煲.当前阶段 =
                焖饭

            电饭煲.剩余时间 =
                参数.焖饭时间 * 60

        end


    # --------------------------------------------------------
    # 焖饭
    # --------------------------------------------------------

    elseif 电饭煲.当前阶段 == 焖饭

        温度控制!(
            电饭煲,
            96.0
        )

        if 电饭煲.剩余时间 <= 0

            电饭煲.当前阶段 =
                保温

        end


    # --------------------------------------------------------
    # 保温
    # --------------------------------------------------------

    elseif 电饭煲.当前阶段 == 保温

        温度控制!(
            电饭煲,
            参数.保温温度
        )

    end

end


# ============================================================
# 15. 显示状态
# ============================================================

function 显示状态(
    电饭煲::智能电饭煲
)

    阶段名称 =
        string(
            电饭煲.当前阶段
        )


    println(
        "----------------------------------------"
    )

    println(
        "烹饪模式：",
        电饭煲.烹饪模式
    )

    println(
        "阶段：",
        阶段名称
    )

    println(
        "锅内温度：",
        round(
            电饭煲.传感器.锅内温度,
            digits=1
        ),
        " °C"
    )

    println(
        "锅底温度：",
        round(
            电饭煲.传感器.锅底温度,
            digits=1
        ),
        " °C"
    )

    println(
        "蒸汽压力：",
        round(
            电饭煲.传感器.蒸汽压力,
            digits=2
        )
    )

    println(
        "加热功率：",
        round(
            电饭煲.加热器.当前功率,
            digits=0
        ),
        " W"
    )

    println(
        "剩余时间：",
        round(
            电饭煲.剩余时间 / 60,
            digits=1
        ),
        " 分钟"
    )

end


# ============================================================
# 16. 完整运行循环
# ============================================================

function 运行电饭煲!(
    电饭煲::智能电饭煲;
    时间步长::Float64=1.0,
    最大运行时间::Float64=3600.0
)

    运行时间 = 0.0

    while 运行时间 <
          最大运行时间

        # 安全检查
        if !安全检查!(
            电饭煲
        )

            println(
                "⚠ 系统停止：",
                电饭煲.错误信息
            )

            break

        end


        # 状态机
        更新烹饪状态!(
            电饭煲,
            时间步长
        )


        # 热力学模拟
        更新温度!(
            电饭煲,
            时间步长
        )


        # 压力计算
        更新压力!(
            电饭煲
        )


        # 每10秒显示一次
        if mod(
            round(Int, 运行时间),
            10
        ) == 0

            显示状态(
                电饭煲
            )

        end


        # 烹饪完成
        if 电饭煲.当前阶段 == 保温 &&
           运行时间 > 1800

            println(
                "🍚 米饭已经完成，进入保温模式。"
            )

            break

        end


        sleep(时间步长)

        运行时间 += 时间步长

    end

end


